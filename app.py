"""
Smart Multi-Document Compliance & Contract Auditor
===================================================

A Streamlit web app that lets legal/finance/compliance teams upload multiple
PDF contracts or policy documents, ask natural-language questions across all
of them, and get answers that are:
  1. Grounded strictly in the uploaded text (Retrieval-Augmented Generation)
  2. Cited back to the exact source paragraph and document
  3. Fact-checked by a second "Corrective RAG" validation pass before display

Pipeline:
  PDF(s) -> pypdf text extraction -> RecursiveCharacterTextSplitter chunks
        -> Sentence-Transformer embeddings -> FAISS vector index
        -> similarity search -> Groq LLM answer generation
        -> Groq LLM validation ("does the context actually support this?")
        -> Streamlit UI (answer + validation verdict + cited source chunks)

Author: Generated for the Smart Multi-Document Compliance & Contract Auditor project.
"""

