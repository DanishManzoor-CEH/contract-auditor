@dataclass
class Chunk:
    """A single retrievable unit of text with citation metadata."""

    text: str
    source_file: str
    page_number: int
    chunk_id: int


@dataclass
class VectorStore:
    """In-memory FAISS index paired with chunk metadata."""

    index: "faiss.IndexFlatL2" = None
    chunks: List[Chunk] = field(default_factory=list)
    dimension: int = 0

    def is_empty(self) -> bool:
        return self.index is None or len(self.chunks) == 0


