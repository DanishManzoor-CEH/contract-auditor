    steps = [
        ("1", "Document intake"),
        ("2", "Semantic indexing"),
        ("3", "Compliance query"),
        ("4", "Validated answer"),
    ]

    parts = []

    for index, (number, label) in enumerate(steps, start=1):

        active = "active" if index <= active_step else ""

        parts.append(
            f"""
            <div class="workflow-step {active}">
                <span class="workflow-number">{number}</span>
                <span>{label}</span>
            </div>
            """
        )

        if index < len(steps):

            parts.append(
                '<div class="workflow-line"></div>'
            )

    st.markdown(
        f'<div class="workflow">{"".join(parts)}</div>',
        unsafe_allow_html=True,
    )


