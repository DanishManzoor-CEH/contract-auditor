# --------------------------------------------------------------------------
# PDF extraction
# --------------------------------------------------------------------------

def extract_text_by_page(
    file_bytes: bytes,
    filename: str
) -> List[Tuple[int, str]]:

    pages = []

    try:
        reader = PdfReader(io.BytesIO(file_bytes))

        for i, page in enumerate(reader.pages, start=1):

            try:
                text = page.extract_text() or ""

                if text.strip():
                    pages.append((i, text))
                else:
                    logger.warning(
                        "No extractable text on page %d of %s",
                        i,
                        filename,
                    )

            except Exception as page_err:
                logger.error(
                    "Failed to extract page %d of %s: %s",
                    i,
                    filename,
                    page_err,
                )

    except Exception as e:
        logger.error("Failed to read PDF %s: %s", filename, e)

        raise ValueError(
            f"Could not read '{filename}'. Is it a valid PDF? ({e})"
        ) from e

    return pages


# --------------------------------------------------------------------------
# Chunking
# --------------------------------------------------------------------------

def chunk_documents(uploaded_files) -> List[Chunk]:

    splitter = RecursiveCharacterTextSplitter(
        chunk_size=CHUNK_SIZE,
        chunk_overlap=CHUNK_OVERLAP,
        separators=[
            "\n\n",
            "\n",
            ". ",
            " ",
            "",
        ],
    )

    all_chunks: List[Chunk] = []
    chunk_id_counter = 0

    for uploaded_file in uploaded_files:

        filename = uploaded_file.name

        try:

            file_bytes = uploaded_file.read()

            pages = extract_text_by_page(
                file_bytes,
                filename,
            )

            if not pages:

                st.warning(
                    f"'{filename}' produced no extractable text. "
                    "It may be a scanned/image-only PDF that needs OCR."
                )

                continue

            for page_number, page_text in pages:

                page_chunks = splitter.split_text(page_text)

                for chunk_text in page_chunks:

                    all_chunks.append(
                        Chunk(
                            text=chunk_text,
                            source_file=filename,
                            page_number=page_number,
                            chunk_id=chunk_id_counter,
                        )
                    )

                    chunk_id_counter += 1

        except ValueError as ve:

            st.error(str(ve))

            logger.error(
                "Skipping file %s due to error: %s",
                filename,
                ve,
            )

        except Exception as e:

            st.error(
                f"Unexpected error processing '{filename}': {e}"
            )

            logger.exception(
                "Unexpected error processing %s",
                filename,
            )

    logger.info(
        "Chunked %d total chunks from %d file(s).",
        len(all_chunks),
        len(uploaded_files),
    )

    return all_chunks


# --------------------------------------------------------------------------
# Vector store
# --------------------------------------------------------------------------

def build_vector_store(
    chunks: List[Chunk],
    embedder: SentenceTransformer,
) -> VectorStore:

    if not chunks:
        return VectorStore()

    texts = [c.text for c in chunks]

    logger.info(
        "Embedding %d chunks...",
        len(texts),
    )

    embeddings = embedder.encode(
        texts,
        show_progress_bar=False,
        convert_to_numpy=True,
        normalize_embeddings=True,
    ).astype("float32")

    dimension = embeddings.shape[1]

    index = faiss.IndexFlatL2(dimension)

    index.add(embeddings)

    logger.info(
        "FAISS index built with dimension %d.",
        dimension,
    )

    return VectorStore(
        index=index,
        chunks=chunks,
        dimension=dimension,
    )


# --------------------------------------------------------------------------
# Retrieval
# --------------------------------------------------------------------------

def retrieve_top_chunks(
    query: str,
    store: VectorStore,
    embedder: SentenceTransformer,
    k: int = TOP_K_RESULTS,
) -> List[Chunk]:

    if store.is_empty():
        return []

    query_vec = embedder.encode(
        [query],
        convert_to_numpy=True,
        normalize_embeddings=True,
    ).astype("float32")

    k = min(
        k,
        len(store.chunks),
    )

    distances, indices = store.index.search(
        query_vec,
        k,
    )

    results = []

    for idx in indices[0]:

        if 0 <= idx < len(store.chunks):
            results.append(
                store.chunks[idx]
            )

    return results


# --------------------------------------------------------------------------
# Context formatting
# --------------------------------------------------------------------------

def format_context(chunks: List[Chunk]) -> str:

    blocks = []

    for c in chunks:

        blocks.append(
            f"[Source: {c.source_file}, Page {c.page_number}]\n"
            f"{c.text}"
        )

    return "\n\n---\n\n".join(blocks)


# --------------------------------------------------------------------------
# Answer generation
# --------------------------------------------------------------------------

def generate_answer(
    client: Groq,
    question: str,
    context: str,
) -> str:

    try:

        response = client.chat.completions.create(
            model=GROQ_MODEL_NAME,
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_ANSWER_PROMPT,
                },
                {
                    "role": "user",
                    "content": (
                        f"CONTEXT:\n{context}\n\n"
                        f"QUESTION:\n{question}"
                    ),
                },
            ],
            temperature=0.1,
            max_tokens=1024,
        )

        return response.choices[0].message.content.strip()

    except Exception as e:

        logger.exception(
            "Groq answer generation failed"
        )

        raise RuntimeError(
            f"Answer generation failed: {e}"
        ) from e


# --------------------------------------------------------------------------
# Corrective RAG validation
# --------------------------------------------------------------------------

def validate_answer(
    client: Groq,
    question: str,
    context: str,
    draft_answer: str,
) -> str:

    try:

        response = client.chat.completions.create(
            model=GROQ_MODEL_NAME,
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_VALIDATION_PROMPT,
                },
                {
                    "role": "user",
                    "content": (
                        f"CONTEXT:\n{context}\n\n"
                        f"QUESTION:\n{question}\n\n"
                        f"DRAFT ANSWER:\n{draft_answer}"
                    ),
                },
            ],
            temperature=0.0,
            max_tokens=400,
        )

        return response.choices[0].message.content.strip()

    except Exception as e:

        logger.exception(
            "Groq validation call failed"
        )

        return (
            "VERDICT: UNKNOWN\n"
            "MISSING_OR_INCORRECT: N/A\n"
            f"NOTE: Validation step failed ({e}); "
            "please review sources manually."
        )


# --------------------------------------------------------------------------
# Verdict parser
# --------------------------------------------------------------------------

def parse_verdict(validation_text: str) -> str:

    for line in validation_text.splitlines():

        if line.upper().startswith("VERDICT:"):

            return (
                line
                .split(":", 1)[1]
                .strip()
                .upper()
            )

    return "UNKNOWN"


def extract_validation_note(validation_text: str) -> str:

    for line in validation_text.splitlines():

        if line.upper().startswith("NOTE:"):

            return line.split(
                ":",
                1,
            )[1].strip()

    return ""


def extract_missing_claims(validation_text: str) -> str:

    for line in validation_text.splitlines():

        if line.upper().startswith(
            "MISSING_OR_INCORRECT:"
        ):

            return line.split(
                ":",
                1,
            )[1].strip()

    return "None"


