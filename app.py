# --------------------------------------------------------------------------
# Step 1: PDF ingestion & text extraction
# --------------------------------------------------------------------------
def extract_text_by_page(file_bytes: bytes, filename: str) -> List[Tuple[int, str]]:
    """
    Extract text from a PDF, page by page, using pypdf.

    Returns a list of (page_number, page_text) tuples. Pages that fail to
    extract (e.g. scanned/image-only pages with no text layer) are logged
    and skipped rather than crashing the whole ingestion run.
    """
    pages = []
    try:
        reader = PdfReader(io.BytesIO(file_bytes))
        for i, page in enumerate(reader.pages, start=1):
            try:
                text = page.extract_text() or ""
                if text.strip():
                    pages.append((i, text))
                else:
                    logger.warning(
                        "No extractable text on page %d of %s (possibly scanned/image PDF).",
                        i, filename,
                    )
            except Exception as page_err:  # noqa: BLE001
                logger.error("Failed to extract page %d of %s: %s", i, filename, page_err)
    except Exception as e:  # noqa: BLE001
        logger.error("Failed to read PDF %s: %s", filename, e)
        raise ValueError(f"Could not read '{filename}'. Is it a valid PDF? ({e})") from e
    return pages


# --------------------------------------------------------------------------
# Step 2: Chunking
# --------------------------------------------------------------------------
def chunk_documents(uploaded_files) -> List[Chunk]:
    """
    Extract and chunk text from all uploaded PDFs.

    Uses RecursiveCharacterTextSplitter (1000 chars, 200 overlap) so that
    each chunk is small enough for accurate embedding/retrieval but still
    carries enough surrounding context to be readable as a standalone
    citation.
    """
    splitter = RecursiveCharacterTextSplitter(
        chunk_size=CHUNK_SIZE,
        chunk_overlap=CHUNK_OVERLAP,
        separators=["\n\n", "\n", ". ", " ", ""],
    )

    all_chunks: List[Chunk] = []
    chunk_id_counter = 0

    for uploaded_file in uploaded_files:
        filename = uploaded_file.name
        try:
            file_bytes = uploaded_file.read()
            pages = extract_text_by_page(file_bytes, filename)

            if not pages:
                st.warning(
                    f"'{filename}' produced no extractable text. "
                    f"It may be a scanned/image-only PDF that needs OCR first."
                )
                continue

            for page_number, page_text in pages:
                page_chunks = splitter.split_text(page_text)
                for chunk_text in page_chunks:
                    all_chunks.append(
                        Chunk(
                            text=chunk_text,
                            source_file=filename,
                            page_number=page_number,
                            chunk_id=chunk_id_counter,
                        )
                    )
                    chunk_id_counter += 1

        except ValueError as ve:
            st.error(str(ve))
            logger.error("Skipping file %s due to error: %s", filename, ve)
        except Exception as e:  # noqa: BLE001
            st.error(f"Unexpected error processing '{filename}': {e}")
            logger.exception("Unexpected error processing %s", filename)

    logger.info("Chunked %d total chunks from %d file(s).", len(all_chunks), len(uploaded_files))
    return all_chunks


# --------------------------------------------------------------------------
# Step 3: Embedding generation & FAISS indexing
# --------------------------------------------------------------------------
def build_vector_store(chunks: List[Chunk], embedder: SentenceTransformer) -> VectorStore:
    """
    Embed every chunk and load the vectors into a flat L2 FAISS index.

    IndexFlatL2 does an exact (brute-force) search, which is perfectly fast
    for the chunk volumes typical of a handful of contracts (thousands of
    chunks), and keeps the code simple and dependency-light versus an
    approximate index.
    """
    if not chunks:
        return VectorStore()

    texts = [c.text for c in chunks]
    logger.info("Embedding %d chunks...", len(texts))
    embeddings = embedder.encode(
        texts,
        show_progress_bar=False,
        convert_to_numpy=True,
        normalize_embeddings=True,  # cosine similarity via normalized L2
    ).astype("float32")

    dimension = embeddings.shape[1]
    index = faiss.IndexFlatL2(dimension)
    index.add(embeddings)

    logger.info("FAISS index built with dimension %d.", dimension)
    return VectorStore(index=index, chunks=chunks, dimension=dimension)


# --------------------------------------------------------------------------
# Step 4: Retrieval
# --------------------------------------------------------------------------
def retrieve_top_chunks(
    query: str, store: VectorStore, embedder: SentenceTransformer, k: int = TOP_K_RESULTS
) -> List[Chunk]:
    """Embed the user query and return the top-k most similar chunks."""
    if store.is_empty():
        return []

    query_vec = embedder.encode(
        [query], convert_to_numpy=True, normalize_embeddings=True
    ).astype("float32")

    k = min(k, len(store.chunks))
    distances, indices = store.index.search(query_vec, k)

    results = []
    for idx in indices[0]:
        if 0 <= idx < len(store.chunks):
            results.append(store.chunks[idx])
    return results


def format_context(chunks: List[Chunk]) -> str:
    """Turn retrieved chunks into a labeled context block for the LLM prompt."""
    blocks = []
    for c in chunks:
        blocks.append(
            f"[Source: {c.source_file}, Page {c.page_number}]\n{c.text}"
        )
    return "\n\n---\n\n".join(blocks)


# --------------------------------------------------------------------------
# Step 5: Groq answer generation
# --------------------------------------------------------------------------
def generate_answer(client: Groq, question: str, context: str) -> str:
    """Call Groq's chat completion API to produce a grounded answer."""
    try:
        response = client.chat.completions.create(
            model=GROQ_MODEL_NAME,
            messages=[
                {"role": "system", "content": SYSTEM_ANSWER_PROMPT},
                {
                    "role": "user",
                    "content": f"CONTEXT:\n{context}\n\nQUESTION:\n{question}",
                },
            ],
            temperature=0.1,
            max_tokens=1024,
        )
        return response.choices[0].message.content.strip()
    except Exception as e:  # noqa: BLE001
        logger.exception("Groq answer generation failed")
        raise RuntimeError(f"Answer generation failed: {e}") from e


# --------------------------------------------------------------------------
# Step 6: Corrective RAG validation pass
# --------------------------------------------------------------------------
def validate_answer(client: Groq, question: str, context: str, draft_answer: str) -> str:
    """
    Second LLM call that checks the draft answer against the retrieved
    context only, and flags unsupported or missing claims. This is the
    "Corrective RAG" step that catches hallucinations before the user sees
    them.
    """
    try:
        response = client.chat.completions.create(
            model=GROQ_MODEL_NAME,
            messages=[
                {"role": "system", "content": SYSTEM_VALIDATION_PROMPT},
                {
                    "role": "user",
                    "content": (
                        f"CONTEXT:\n{context}\n\n"
                        f"QUESTION:\n{question}\n\n"
                        f"DRAFT ANSWER:\n{draft_answer}"
                    ),
                },
            ],
            temperature=0.0,
            max_tokens=400,
        )
        return response.choices[0].message.content.strip()
    except Exception as e:  # noqa: BLE001
        logger.exception("Groq validation call failed")
        # Validation failing should not block the user from seeing the
        # answer -- degrade gracefully with a clear note instead.
        return (
            "VERDICT: UNKNOWN\nMISSING_OR_INCORRECT: N/A\n"
            f"NOTE: Validation step failed ({e}); please review sources manually."
        )


def parse_verdict(validation_text: str) -> str:
    """Pull just the VERDICT line out of the validation response for badge display."""
    for line in validation_text.splitlines():
        if line.upper().startswith("VERDICT:"):
            return line.split(":", 1)[1].strip().upper()
    return "UNKNOWN"


