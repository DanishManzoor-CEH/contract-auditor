def render_verdict(verdict: str, note: str = ""):
    config = VERDICT_STYLE.get(
        verdict,
        VERDICT_STYLE["UNKNOWN"],
    )

    if verdict == "SUPPORTED":
        st.success(
            f"**{config['label']}**\n\n"
            f"{note or config['description']}",
            icon="✓",
        )
    elif verdict == "PARTIALLY_SUPPORTED":
        st.warning(
            f"**{config['label']}**\n\n"
            f"{note or config['description']}",
            icon="◐",
        )
    elif verdict == "NOT_SUPPORTED":
        st.error(
            f"**{config['label']}**\n\n"
            f"{note or config['description']}",
            icon="✕",
        )
    elif verdict == "NOT_IN_DOCUMENT":
        st.info(
            f"**{config['label']}**\n\n"
            f"{note or config['description']}",
            icon="i",
        )
    else:
        st.warning(
            f"**{config['label']}**\n\n"
            f"{note or config['description']}",
            icon="?",
        )


def render_sources(sources: List[Chunk]):
    st.markdown(
        f"### Evidence Exhibits ({len(sources)})"
    )

    for index, chunk in enumerate(sources, start=1):
        st.markdown(
            f"""
            <div class="source-card">
                <div class="source-title">
                    [{index}] {safe(chunk.source_file)}
                </div>
                <div>
                    {safe(chunk.text)}
                </div>
                <div class="source-meta">
                    Page {chunk.page_number} · Chunk {chunk.chunk_id}
                </div>
            </div>
            """,
            unsafe_allow_html=True,
        )


def render_answer_block(entry: dict):
    verdict = entry["verdict"]

    note = extract_validation_note(
        entry["validation_raw"]
    )

    missing = extract_missing_claims(
        entry["validation_raw"]
    )

    st.markdown(
        '<div class="answer-card">',
        unsafe_allow_html=True,
    )

    st.markdown(
        '<div class="answer-label">Compliance Analysis</div>',
        unsafe_allow_html=True,
    )

    st.markdown(
        f'<div class="question-text">{safe(entry["question"])}</div>',
        unsafe_allow_html=True,
    )

    st.markdown("</div>", unsafe_allow_html=True)

    st.markdown(entry["answer"])

    render_verdict(verdict, note)

    with st.expander("Review validation findings"):
        st.write(
            "The validation model compared the generated answer "
            "against the retrieved source context."
        )

        st.markdown("**Missing or incorrect claims**")
        st.info(missing)

        st.markdown("**Raw validation response**")
        st.code(
            entry["validation_raw"],
            language="text",
        )

    with st.expander(
        f"View source evidence ({len(entry['sources'])})"
    ):
        render_sources(entry["sources"])


def render_history():
    if not st.session_state.history:
        return

    with st.expander(
        f"Query history ({len(st.session_state.history)})"
    ):
        for item in st.session_state.history:
            config = VERDICT_STYLE.get(
                item["verdict"],
                VERDICT_STYLE["UNKNOWN"],
            )

            st.markdown(
                f"**{item['question']}**"
            )

            st.caption(
                f"{config['icon']} {config['label']} · "
                f"{len(item['sources'])} source(s)"
            )

            st.divider()


def render_main(
    client_available: bool,
    embedder: SentenceTransformer,
):
    render_header(client_available)

    render_workflow(
        active_step=4
        if not st.session_state.vector_store.is_empty()
        else 1
    )

    if st.session_state.vector_store.is_empty():
        st.markdown(
            """
            <div class="card">
                <div class="section-kicker">Evidence workspace</div>
                <div class="section-heading">
                    Your evidence workspace is empty
                </div>
                <div class="section-copy">
                    Upload one or more contract or policy PDFs from the
                    sidebar. The application will extract text, create
                    semantic embeddings, index the evidence with FAISS,
                    and make it available for grounded questions.
                </div>
            </div>
            """,
            unsafe_allow_html=True,
        )

        st.markdown("### How the analysis works")

        cols = st.columns(3)

        with cols[0]:
            st.info(
                "**01 · Retrieve**\n\n"
                "Relevant passages are retrieved from the uploaded documents."
            )

        with cols[1]:
            st.info(
                "**02 · Generate**\n\n"
                "The answer is generated from the retrieved document context."
            )

        with cols[2]:
            st.info(
                "**03 · Validate**\n\n"
                "A second model pass checks whether the answer is supported."
            )

        return

    render_stats()

    if not client_available:
        st.error(
            "GROQ_API_KEY is not configured. "
            "Add it to Streamlit secrets before submitting a question."
        )

    st.markdown(
        '<div class="section-kicker">01 · Compliance Query</div>',
        unsafe_allow_html=True,
    )

    st.markdown(
        '<div class="section-heading">Ask across your evidence base</div>',
        unsafe_allow_html=True,
    )

    st.markdown(
        '<div class="section-copy">'
        'Ask about obligations, dates, penalties, termination, payment terms, '
        'security requirements, or differences across the uploaded documents.'
        '</div>',
        unsafe_allow_html=True,
    )

    question = st.text_area(
        "Compliance question",
        placeholder=(
            "Example: What is the termination notice period "
            "across all vendor contracts?"
        ),
        height=120,
        label_visibility="collapsed",
    )

    st.caption(
        "Tip: Ask about a specific clause, obligation, date, amount, "
        "party, or comparison."
    )

    st.markdown("**Suggested queries**")

    examples = [
        "What are the termination notice periods?",
        "Which contracts contain indemnification clauses?",
        "What payment deadlines are specified?",
        "Are there any data security obligations?",
    ]

    cols = st.columns(4)

    for col, example in zip(cols, examples):
        with col:
            if st.button(
                example,
                key=f"example_{example}",
                use_container_width=True,
            ):
                question = example

    ask_disabled = (
        not client_available
        or not question.strip()
    )

    if st.button(
        "Analyze with Evidence",
        type="primary",
        disabled=ask_disabled,
        use_container_width=True,
    ):
        try:
            client = get_groq_client()
        except RuntimeError as e:
            st.error(str(e))
            return

        with st.status(
            "Running compliance analysis...",
            expanded=True,
        ) as status:
            st.write("Searching the evidence base...")

            top_chunks = retrieve_top_chunks(
                question,
                st.session_state.vector_store,
                embedder,
            )

            if not top_chunks:
                status.update(
                    label="No relevant evidence found",
                    state="complete",
                )

                st.info(
                    "The indexed documents do not contain enough relevant "
                    "text for this question. This is an informational result, "
                    "not a system error."
                )
                return

            st.write(
                f"Retrieved {len(top_chunks)} relevant evidence chunks."
            )

            context = format_context(top_chunks)

            st.write("Generating a grounded answer...")

            try:
                draft_answer = generate_answer(
                    client,
                    question,
                    context,
                )
            except RuntimeError as e:
                status.update(
                    label="Answer generation failed",
                    state="error",
                )
                st.error(str(e))
                return

            st.write("Running Corrective RAG validation...")

            validation_raw = validate_answer(
                client,
                question,
                context,
                draft_answer,
            )

            verdict = parse_verdict(validation_raw)

            status.update(
                label="Analysis complete",
                state="complete",
            )

        entry = {
            "question": question,
            "answer": draft_answer,
            "validation_raw": validation_raw,
            "verdict": verdict,
            "sources": top_chunks,
        }

        st.session_state.history.insert(
            0,
            entry,
        )

    if st.session_state.history:
        st.divider()

        st.markdown(
            '<div class="section-kicker">02 · Review Results</div>',
            unsafe_allow_html=True,
        )

        st.markdown(
            '<div class="section-heading">Evidence-backed analysis</div>',
            unsafe_allow_html=True,
        )

        st.markdown(
            '<div class="section-copy">'
            'Review the generated answer, validation verdict, and evidence '
            'used to support the result.'
            '</div>',
            unsafe_allow_html=True,
        )

        for entry in st.session_state.history:
            render_answer_block(entry)

        render_history()

    st.markdown(
        '<div class="footer-note">'
        'Contract Auditor · Evidence-first compliance analysis · '
        'Supported · Partially supported · Not supported · Not in document'
        '</div>',
        unsafe_allow_html=True,
    )


